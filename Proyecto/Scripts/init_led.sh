# Wake + modo normal
i2cset -y 2 0x60 0x00 0x00      # MODE1: SLEEP=0
i2cset -y 2 0x60 0x01 0x04      # MODE2: totem-pole, DMBLNK=0

# Corriente en TODOS los canales (0..15) = máx (si están en 0, no verás luz)
for i in $(seq 0 15); do
  addr=$(printf "0x%X" $((0x40 + i)))
  i2cset -y 2 0x60 $addr 0xFF
done

# LEDOUT0..3 = 0xAA => los 16 canales en "PWM individual"
i2cset -y 2 0x60 0x02 0xAA
i2cset -y 2 0x60 0x03 0xAA
i2cset -y 2 0x60 0x04 0xAA
i2cset -y 2 0x60 0x05 0xAA

# (Opcional) Desactiva cualquier control de grupo
i2cset -y 2 0x60 0x06 0x00      # GRPPWM
i2cset -y 2 0x60 0x07 0x00      # GRPFREQ

# Enciende algunos canales (ej. PWM0 y PWM1)
i2cset -y 2 0x60 0x08 0xFF      # PWM0
i2cset -y 2 0x60 0x09 0xFF      # PWM1


i2cset -y 2 0x60 0x02 0x00
i2cset -y 2 0x60 0x03 0x00
i2cset -y 2 0x60 0x04 0x00
i2cset -y 2 0x60 0x05 0x00
